"""PlatformIO pre-script: stamps the firmware with its git commit.

Writes $BUILD_DIR/generated/belt_build_id.h with
  BELT_BUILD_ID   first 8 hex digits of HEAD as a u32 (0 = unknown), for the status characteristic
  BELT_BUILD_STR  the same digits as text, "+" appended if esp32/ has uncommitted changes
                  to tracked files ("unknown" without git), for the info characteristic

The header is only rewritten when its content changes, so only main.cpp recompiles.
"""

import os
import subprocess

Import("env")  # noqa: F821 - provided by PlatformIO/SCons


def _git(*args):
    try:
        out = subprocess.run(
            ["git", *args], cwd=env.subst("$PROJECT_DIR"), capture_output=True, text=True, check=True, timeout=10
        )
    except Exception:  # noqa: BLE001 - no git or not a checkout: build anyway, as "unknown"
        return None
    return out.stdout.strip()


sha = _git("rev-parse", "--short=8", "HEAD")
if sha and len(sha) >= 8:
    sha = sha[:8]
    dirty = bool(_git("status", "--porcelain", "--untracked-files=no", "--", "."))
    build_id, build_str = int(sha, 16), sha + ("+" if dirty else "")
else:
    build_id, build_str = 0, "unknown"

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, "belt_build_id.h")
text = (
    "// Generated by scripts/build_id.py. Do not edit or commit.\n"
    "#pragma once\n"
    f"#define BELT_BUILD_ID 0x{build_id:08x}u\n"
    f'#define BELT_BUILD_STR "{build_str}"\n'
)
try:
    with open(path) as f:
        current = f.read()
except OSError:
    current = None
if current != text:
    with open(path, "w") as f:
        f.write(text)
print(f"belt build id: {build_str}")
env.Append(CPPPATH=[out_dir])
